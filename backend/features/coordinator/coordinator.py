"""Coordinator Agent — decompose, orchestrate fan-out + debate, synthesise.

  decompose(profile)                  -> dict[str, str]   (6 sub_tasks)
  synthesise(outputs, critic, profile)-> FinalPlan
  run(profile, ...)                   -> FinalPlan         (full pipeline)

The pipeline emits TraceEvents at every step so the live Agent Trace View can
follow along. The system hard-requires GEMINI_API_KEY: decompose and synthesise
call Gemini directly and fail fast (no offline fallback) when the model returns
nothing usable, surfacing the failure as an ERROR trace event.
"""

from __future__ import annotations

import asyncio
import time
import uuid

from features.agents.base import (
    AgentParseError,
    SessionContext,
    call_claude,
    extract_json,
)
from features.coordinator.prompts import (
    COORDINATOR_DECOMPOSE_SYSTEM,
    SYNTHESIS_SYSTEM_PROMPT,
)
from features.debate.critique_loop import AGENT_RUNNERS, run_debate
from features.trace.logger import Tracer
from schemas.agent_schemas import (
    AgentOutput,
    FinalPlan,
    TraceEventType,
    UserProfile,
)

DISCLAIMER = (
    "This plan is generated by an AI system for educational purposes only and is "
    "not a substitute for professional medical advice, diagnosis, or treatment. "
    "Consult a qualified healthcare provider before starting any diet or exercise "
    "programme, especially if you have a medical condition."
)

_RISK_PENALTY = {"low": 0.0, "medium": 1.5, "high": 3.5, "critical": 6.0}

# ---------------------------------------------------------------------------
# Agent-to-agent communication
#
# Specialists no longer run as one blind parallel wave. They run as a dependency
# pipeline: each agent receives the structured outputs of the agents it depends
# on (threaded in as `peer_context`), so conclusions flow downstream — Macros'
# targets shape Nutrition's meals, Nutrition + Fitness costs feed Budget, and
# Risk screens everything. After the draft, a cross-examination round lets every
# agent validate or challenge its peers' conclusions and revise to reconcile.
# ---------------------------------------------------------------------------

# agent -> the upstream agents whose structured output it consumes.
DEPENDENCIES: dict[str, tuple[str, ...]] = {
    "macros": (),  # pure Mifflin–St Jeor computation from the profile
    "fitness": (),  # training programme from goal / activity / gym access
    "nutrition": ("macros", "fitness"),  # meals must hit macro targets & fuel training
    "budget": ("nutrition", "fitness"),  # price the actual foods + gym/supplements
    "risk": ("macros", "fitness", "nutrition", "budget"),  # screens every draft
}

# Topological layering of DEPENDENCIES. Agents within a stage run in parallel;
# stages run in order so dependents see their upstreams' outputs.
PIPELINE_STAGES: tuple[tuple[str, ...], ...] = (
    ("macros", "fitness"),
    ("nutrition",),
    ("budget",),
    ("risk",),
)

CROSS_EXAM_DIRECTIVE = (
    "\n\nCROSS-EXAMINATION ROUND. Your peers' structured conclusions are provided "
    "as peer context above. For every peer conclusion that touches your domain, "
    "decide whether you VALIDATE it (consistent and sound) or CHALLENGE it (state "
    "the specific conflict and the concrete change you would request). Then REVISE "
    "your own output so it is fully consistent with the conclusions you validated. "
    "Keep your JSON response schema EXACTLY the same; record each validation or "
    "challenge as a short string in the 'flags' array, prefixed with 'validate:' "
    "or 'challenge:' and naming the peer (e.g. 'challenge:budget — ...')."
)


async def _run_agent_timed(
    name: str,
    sub_task: str,
    profile: UserProfile,
    *,
    peer_context: dict | None,
    round: int,
    session: SessionContext,
) -> tuple[AgentOutput, float]:
    """Run one specialist, returning its output and wall-clock duration (ms)."""
    t0 = time.perf_counter()
    out = await AGENT_RUNNERS[name](
        sub_task,
        profile,
        peer_context=peer_context or None,
        round=round,
        session_context=session,
    )
    return out, (time.perf_counter() - t0) * 1000.0


def _completed_payload(out: AgentOutput, **extra: object) -> dict:
    """Rich AGENT_COMPLETED payload consumed by the Step-Detail drawer."""
    payload = {
        "verdict": out.verdict,
        "reasoning": out.reasoning,
        "output": out.data,
        "sources": out.data.get("sources", []),
        "confidence": out.confidence,
        "flags": out.flags,
    }
    payload.update(extra)
    return payload


async def _run_pipeline(
    sub_tasks: dict[str, str],
    profile: UserProfile,
    session: SessionContext,
    tracer: Tracer,
) -> dict[str, AgentOutput]:
    """Run the specialists as a dependency pipeline (round 1 drafts).

    Each agent receives its upstream dependencies' structured outputs as
    peer_context; the emitted trace edges (peer_context_agents) are the real
    dependency edges the graph renders."""
    outputs: dict[str, AgentOutput] = {}

    for stage in PIPELINE_STAGES:
        for name in stage:
            deps = DEPENDENCIES[name]
            await tracer.emit(
                TraceEventType.AGENT_STARTED,
                agent_name=name,
                round=1,
                payload={
                    "input": sub_tasks[name],
                    "peer_context_agents": list(deps),
                    "round": 1,
                },
            )

        async def _one(name: str) -> tuple[str, AgentOutput | None, float, Exception | None]:
            deps = DEPENDENCIES[name]
            peer_context = {d: outputs[d].data for d in deps if d in outputs}
            try:
                out, dur = await _run_agent_timed(
                    name, sub_tasks[name], profile,
                    peer_context=peer_context, round=1, session=session,
                )
                return name, out, dur, None
            except Exception as exc:  # noqa: BLE001 — isolate one agent's failure
                return name, None, 0.0, exc

        for name, out, dur, exc in await asyncio.gather(*(_one(n) for n in stage)):
            if exc is not None or out is None:
                await tracer.emit(
                    TraceEventType.ERROR,
                    agent_name=name,
                    message=f"{type(exc).__name__}: {exc}",
                )
                continue
            outputs[name] = out
            await tracer.emit(
                TraceEventType.AGENT_COMPLETED,
                agent_name=name,
                round=1,
                message=out.verdict,
                payload=_completed_payload(out, peer_context_agents=list(DEPENDENCIES[name])),
                duration_ms=dur,
            )

    session.record_outputs(1, outputs)
    return outputs


async def _cross_examine(
    sub_tasks: dict[str, str],
    profile: UserProfile,
    drafts: dict[str, AgentOutput],
    session: SessionContext,
    tracer: Tracer,
) -> dict[str, AgentOutput]:
    """Round 2: every agent validates or challenges its peers and refines.

    Each agent re-runs with the *full* set of peer outputs and the
    cross-examination directive; the refined outputs feed the Critic debate."""
    names = [n for n in DEPENDENCIES if n in drafts]
    if len(names) < 2:
        return drafts  # nothing to cross-examine against

    for name in names:
        peers = [n for n in names if n != name]
        await tracer.emit(
            TraceEventType.AGENT_STARTED,
            agent_name=name,
            round=2,
            message="Cross-examining peers",
            payload={
                "input": sub_tasks[name] + CROSS_EXAM_DIRECTIVE,
                "peer_context_agents": peers,
                "round": 2,
            },
        )

    async def _one(name: str) -> tuple[str, AgentOutput | None, float, Exception | None]:
        peers = {n: drafts[n].data for n in names if n != name}
        try:
            out, dur = await _run_agent_timed(
                name, sub_tasks[name] + CROSS_EXAM_DIRECTIVE, profile,
                peer_context=peers, round=2, session=session,
            )
            return name, out, dur, None
        except Exception as exc:  # noqa: BLE001 — keep the draft on failure
            return name, None, 0.0, exc

    refined: dict[str, AgentOutput] = dict(drafts)
    for name, out, dur, exc in await asyncio.gather(*(_one(n) for n in names)):
        if exc is not None or out is None:
            continue  # keep the round-1 draft for this agent
        refined[name] = out
        challenges = [f for f in out.flags if f.lower().startswith(("challenge", "validate"))]
        await tracer.emit(
            TraceEventType.AGENT_COMPLETED,
            agent_name=name,
            round=2,
            message=out.verdict,
            payload=_completed_payload(
                out,
                revised=True,
                phase="cross_examination",
                peer_context_agents=[n for n in names if n != name],
                challenges=challenges,
            ),
            duration_ms=dur,
        )

    session.record_outputs(2, refined)
    return refined


