def _health_score(
    by_name: dict[str, AgentOutput], consistency: float, final_safe: bool
) -> float:
    score = 10.0
    risk = by_name.get("risk")
    if risk:
        level = str(risk.data.get("overall_risk_level", "low"))
        score -= _RISK_PENALTY.get(level, 0.0)
    budget = by_name.get("budget")
    if budget and budget.data.get("within_budget") is False:
        score -= 1.0
    score -= (1.0 - consistency) * 2.0
    if not final_safe:
        score -= 2.0
    return round(max(0.0, min(10.0, score)), 1)


async def _llm_narrative(
    profile: UserProfile,
    by_name: dict[str, AgentOutput],
    critic: AgentOutput,
) -> tuple[str, list[str], list[str]]:
    """Generate the synthesis narrative via Gemini.

    Raises AgentParseError on an incomplete narrative — there is no offline
    fallback, so a failure here surfaces as a pipeline ERROR rather than canned
    prose.
    """
    payload = {
        "profile": profile.model_dump(),
        "agent_outputs": {n: o.data for n, o in by_name.items()},
        "qa_review": critic.data,
    }
    raw = await call_claude(
        SYNTHESIS_SYSTEM_PROMPT,
        f"Synthesise a plan from:\n{payload}",
        temperature=0.5,
        max_tokens=1500,
        prefill="{",
    )
    parsed = extract_json(raw)
    summary = str(parsed.get("user_summary", "")).strip()
    insights = [str(x).strip() for x in parsed.get("key_insights", []) if str(x).strip()]
    actions = [str(x).strip() for x in parsed.get("action_steps_week_1", []) if str(x).strip()]
    if not summary or len(insights) < 5 or len(actions) < 7:
        raise AgentParseError(
            "Synthesis narrative incomplete "
            f"(summary={bool(summary)}, insights={len(insights)}, actions={len(actions)})"
        )
    return summary, insights[:5], actions[:7]


async def synthesise(
    agent_outputs: list[AgentOutput],
    critic_output: AgentOutput,
    profile: UserProfile,
    *,
    plan_id: str | None = None,
    debate_rounds: int = 1,
) -> FinalPlan:
    """Assemble the FinalPlan from specialist outputs + the critic's QA."""
    by_name = {o.agent_name: o for o in agent_outputs}
    consistency = float(critic_output.data.get("consistency_score", 1.0))
    final_safe = bool(critic_output.data.get("final_recommendation_safe", True))

    user_summary, key_insights, action_steps = await _llm_narrative(
        profile, by_name, critic_output
    )

    def data_of(name: str) -> dict:
        out = by_name.get(name)
        return dict(out.data) if out else {}

    return FinalPlan(
        plan_id=plan_id or uuid.uuid4().hex,
        user_summary=user_summary,
        overall_health_score=_health_score(by_name, consistency, final_safe),
        nutrition_plan=data_of("nutrition"),
        macros_targets=data_of("macros"),
        fitness_programme=data_of("fitness"),
        risk_assessment=data_of("risk"),
        budget_analysis=data_of("budget"),
        key_insights=key_insights,
        action_steps_week_1=action_steps,
        disclaimer=DISCLAIMER,
        debate_rounds=debate_rounds,
        consistency_score=consistency,
        final_recommendation_safe=final_safe,
    )


# ---------------------------------------------------------------------------
# Full pipeline
# ---------------------------------------------------------------------------


async def run(
    profile: UserProfile,
    max_debate_rounds: int = 3,
    run_id: str | None = None,
    directives: str | None = None,
) -> FinalPlan:
    """decompose -> fan-out (5 agents) -> debate -> synthesise. Emits trace.

    `directives` carries an optional re-plan change request through decomposition.
    """
    run_id = run_id or uuid.uuid4().hex
    tracer = Tracer(run_id)
    session = SessionContext(plan_id=run_id)
    await tracer.emit(TraceEventType.RUN_STARTED, message="Run started")

    try:
        sub_tasks = await decompose(profile, directives)
        await tracer.emit(
            TraceEventType.AGENT_COMPLETED,
            agent_name="coordinator",
            message="Decomposed profile into sub-tasks",
            # The inputs the Coordinator routed to each agent — the graph reads
            # this to label Coordinator -> specialist edges and the step detail.
            payload={"sub_tasks": sub_tasks},
        )

        # Dependency pipeline (round 1 drafts): specialists run in topological
        # stages, each consuming its upstreams' structured outputs as peer
        # context, so conclusions flow Macros/Fitness -> Nutrition -> Budget,
        # with Risk screening every draft.
        drafts = await _run_pipeline(sub_tasks, profile, session, tracer)

        # Cross-examination (round 2): every agent validates or challenges its
        # peers' conclusions and revises to reconcile.
        refined = await _cross_examine(sub_tasks, profile, drafts, session, tracer)
        outputs = list(refined.values())

        # Debate loop (Critic QA + targeted re-runs) over the reconciled outputs.
        debate = await run_debate(
            outputs,
            profile,
            sub_tasks,
            max_rounds=max_debate_rounds,
            tracer=tracer,
            session_context=session,
        )

        # Synthesise the final plan.
        await tracer.emit(
            TraceEventType.SYNTHESIS,
            agent_name="coordinator",
            message="Synthesising final plan",
            # Which agents' outputs feed the synthesis — drives all -> Synthesis edges.
            payload={"inputs_from": [o.agent_name for o in debate.final_outputs]},
        )
        plan = await synthesise(
            debate.final_outputs,
            debate.critic,
            profile,
            plan_id=run_id,
            debate_rounds=debate.rounds,
        )

        # Persist the finished plan so GET /api/plans/{plan_id} can serve it.
        await tracer.save_result(plan)

        await tracer.emit(
            TraceEventType.RUN_COMPLETED,
            agent_name="coordinator",
            message="Plan ready",
            payload={
                "plan_id": plan.plan_id,
                "overall_health_score": plan.overall_health_score,
                "final_recommendation_safe": plan.final_recommendation_safe,
            },
        )
        return plan

    except Exception as exc:
        await tracer.emit(
            TraceEventType.ERROR, message=f"Pipeline failed: {type(exc).__name__}: {exc}"
        )
        raise
